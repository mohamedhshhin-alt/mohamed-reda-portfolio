  var modal = $('#modal');
  var frame = $('#frame');
  var mount = $('#demoMount');
  var overlay = $('#overlayMount');
  var dialog = $('.modal-dialog');
  var lastFocus = null;

  function setDevice(w) {
    frame.setAttribute('data-w', w);
    $$('.devices button').forEach(function (b) { b.setAttribute('aria-pressed', b.getAttribute('data-w') === w ? 'true' : 'false'); });
  }
  function openDemo(id) {
    var def = window.MRDemos && window.MRDemos.items && window.MRDemos.items[id];
    if (!def) return;
    if (current) closeDemo(true);
    lastFocus = document.activeElement;
    $('#modalTitle').textContent = def.title[lang];
    setDevice('desktop');
    mount.innerHTML = '';
    overlay.innerHTML = '';
    modal.hidden = false;
    root.classList.add('lock');
    var inst = null;
    try { inst = def.mount(mount, overlay); } catch (err) { console.error(err); }
    current = { id: id, inst: inst };
    window.requestAnimationFrame(function () { window.requestAnimationFrame(function () { modal.classList.add('open'); }); });
    dialog.focus();
  }
  function closeDemo(instant) {
    if (!current) return;
    var inst = current.inst;
    current = null;
    modal.classList.remove('open');
    function finish() {
      if (inst && inst.destroy) { try { inst.destroy(); } catch (e) { console.error(e); } }
      if (current) return; /* another project was opened meanwhile */
      mount.innerHTML = '';
      overlay.innerHTML = '';
      modal.hidden = true;
      root.classList.remove('lock');
      if (lastFocus && lastFocus.focus) { try { lastFocus.focus(); } catch (e) {} }
    }
    if (instant || reduce) finish(); else window.setTimeout(finish, 340);
  }
  document.addEventListener('click', function (e) {
    var t = e.target;
    if (!t.closest) return;
    var d = t.closest('[data-demo]');
    if (d) { openDemo(d.getAttribute('data-demo')); return; }
    if (t.closest('[data-close]')) { closeDemo(); return; }
    var dv = t.closest('.devices button');
    if (dv) setDevice(dv.getAttribute('data-w'));
  });
  document.addEventListener('keydown', function (e) {
    if (!current) return;
    if (e.key === 'Escape') {
      if (current.inst && current.inst.onEscape && current.inst.onEscape()) return;
      closeDemo();
      return;
    }
    if (e.key === 'Tab') {
      var f = $$('button, [href], input, select, textarea, summary, [tabindex]:not([tabindex="-1"])', dialog).filter(function (el) { return !el.disabled && el.offsetParent !== null; });
      if (!f.length) return;
      var first = f[0], last = f[f.length - 1];
      if (e.shiftKey && (document.activeElement === first || document.activeElement === dialog)) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    }
  });

